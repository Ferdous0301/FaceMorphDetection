"""Identity graph construction for identity-disjoint dataset splitting.

This module provides :class:`IdentityGraph`, a lightweight, dependency-free
graph structure used to model relationships between bona fide identities
and the morph images that combine them. Two identities that are ever
combined into a morph (directly or transitively) must end up in the same
dataset split to avoid identity leakage between splits. This module
computes the connected components that encode that constraint.

The graph uses plain adjacency lists (``dict[str, list[str]]``) and
performs deterministic breadth-first traversal with stable insertion-order
semantics. No external graph libraries and no randomness are used.

This module contains graph-construction logic only; it does not perform
any dataset splitting.
"""

from __future__ import annotations

from collections import deque
from typing import Iterator

from src.dataset_split.exceptions import DatasetSplitError


class UnknownIdentityError(DatasetSplitError):
    """Raised when an operation references an identity not in the graph."""


class IdentityGraph:
    """A deterministic, adjacency-list-based graph of identity relationships.

    Nodes represent bona fide identities. Edges represent morph
    relationships between two identities (i.e. a morph image was
    generated by combining those two identities). Connected components of
    this graph identify sets of identities that must be kept together
    within a single dataset split to prevent identity leakage.

    Traversal order is deterministic: identities and their adjacency
    lists preserve first-seen insertion order, and connected components
    are computed via breadth-first search seeded in insertion order.
    """

    def __init__(self) -> None:
        """Initialize an empty identity graph."""
        self._adjacency: dict[str, list[str]] = {}

    def add_identity(self, identity: str) -> None:
        """Add a bona fide identity to the graph as an isolated node.

        If the identity already exists, this is a no-op. This method
        never removes existing adjacency information.

        Args:
            identity: The unique identifier of the bona fide identity.
        """
        if identity not in self._adjacency:
            self._adjacency[identity] = []

    def add_morph(self, identity_a: str, identity_b: str) -> None:
        """Register a morph relationship between two identities.

        Both identities are added to the graph if not already present,
        and an undirected edge is created between them. Self-morphs
        (an identity morphed with itself) are recorded as an isolated
        node with no edge added. Duplicate edges are ignored.

        Args:
            identity_a: The first identity used to generate the morph.
            identity_b: The second identity used to generate the morph.
        """
        self.add_identity(identity_a)
        self.add_identity(identity_b)

        if identity_a == identity_b:
            return

        if identity_b not in self._adjacency[identity_a]:
            self._adjacency[identity_a].append(identity_b)
        if identity_a not in self._adjacency[identity_b]:
            self._adjacency[identity_b].append(identity_a)

    def identities(self) -> list[str]:
        """Return all identities currently in the graph.

        Returns:
            A list of identity identifiers in first-seen insertion order.
        """
        return list(self._adjacency.keys())

    def connected_components(self) -> list[list[str]]:
        """Compute the connected components of the identity graph.

        Components are computed via breadth-first search, seeded in the
        insertion order of identities. Within each component, identities
        are ordered by the order in which they were first visited during
        traversal, which is fully deterministic given the graph's
        construction history.

        Returns:
            A list of components, each a list of identity identifiers.
            The order of components matches the insertion order of each
            component's earliest-inserted identity.
        """
        visited: set[str] = set()
        components: list[list[str]] = []

        for start in self._adjacency:
            if start in visited:
                continue

            component: list[str] = []
            queue: deque[str] = deque([start])
            visited.add(start)

            while queue:
                current = queue.popleft()
                component.append(current)
                for neighbor in self._adjacency[current]:
                    if neighbor not in visited:
                        visited.add(neighbor)
                        queue.append(neighbor)

            components.append(component)

        return components

    def component_of(self, identity: str) -> list[str]:
        """Return the connected component containing the given identity.

        Args:
            identity: The identity whose component should be returned.

        Returns:
            The list of identities in the same connected component as
            ``identity``, in deterministic traversal order.

        Raises:
            UnknownIdentityError: If ``identity`` is not present in the
                graph.
        """
        if identity not in self._adjacency:
            raise UnknownIdentityError(
                f"Identity {identity!r} is not present in the graph."
            )

        visited: set[str] = {identity}
        queue: deque[str] = deque([identity])
        component: list[str] = []

        while queue:
            current = queue.popleft()
            component.append(current)
            for neighbor in self._adjacency[current]:
                if neighbor not in visited:
                    visited.add(neighbor)
                    queue.append(neighbor)

        return component

    def has_identity(self, identity: str) -> bool:
        """Check whether an identity exists in the graph.

        Args:
            identity: The identity identifier to check.

        Returns:
            ``True`` if the identity has been added to the graph,
            ``False`` otherwise.
        """
        return identity in self._adjacency

    def neighbors(self, identity: str) -> list[str]:
        """Return the identities directly morphed with the given identity.

        Args:
            identity: The identity whose neighbors should be returned.

        Returns:
            A list of directly connected identities, in insertion order.

        Raises:
            UnknownIdentityError: If ``identity`` is not present in the
                graph.
        """
        if identity not in self._adjacency:
            raise UnknownIdentityError(
                f"Identity {identity!r} is not present in the graph."
            )
        return list(self._adjacency[identity])

    def __len__(self) -> int:
        """Return the number of identities in the graph."""
        return len(self._adjacency)

    def __contains__(self, identity: object) -> bool:
        """Support ``identity in graph`` membership checks."""
        return identity in self._adjacency

    def __iter__(self) -> Iterator[str]:
        """Iterate over identities in insertion order."""
        return iter(self._adjacency)